-- Residency context. Lives in the "residency" schema (set by Flyway).
-- user_id belongs to the Identity context: a plain column, no foreign key.
-- Personal data (names, phone numbers) is NOT stored here; a membership only links a user ID to a flat.

CREATE TABLE society (
    id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name  VARCHAR(150) NOT NULL
);

CREATE TABLE tower (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    society_id          BIGINT       NOT NULL REFERENCES society (id),
    code                VARCHAR(10)  NOT NULL,
    name                VARCHAR(100) NOT NULL,
    residential_floors  INTEGER      NOT NULL CHECK (residential_floors BETWEEN 1 AND 99),
    CONSTRAINT uq_tower_code UNIQUE (society_id, code)
);

CREATE TABLE flat (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    society_id  BIGINT   NOT NULL REFERENCES society (id),
    tower_id    BIGINT   NOT NULL REFERENCES tower (id),
    floor       INTEGER  NOT NULL CHECK (floor BETWEEN 1 AND 99),
    unit        INTEGER  NOT NULL CHECK (unit BETWEEN 1 AND 99),
    CONSTRAINT uq_flat_number UNIQUE (tower_id, floor, unit)
);

CREATE INDEX ix_flat_society ON flat (society_id);

CREATE TABLE flat_member (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    flat_id  BIGINT       NOT NULL REFERENCES flat (id),
    user_id  BIGINT       NOT NULL,
    type     VARCHAR(10)  NOT NULL CHECK (type IN ('OWNER', 'TENANT')),
    since    TIMESTAMPTZ  NOT NULL,
    CONSTRAINT uq_flat_member UNIQUE (flat_id, user_id)
);

CREATE INDEX ix_flat_member_user ON flat_member (user_id);
