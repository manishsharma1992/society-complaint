-- Complaint Management context. Lives in the "complaint" schema (set by Flyway).
-- society_id, tower_id, flat_id and user IDs belong to other contexts: plain columns, no foreign keys.

CREATE TABLE complaint_category (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    society_id  BIGINT       NOT NULL,
    name        VARCHAR(100) NOT NULL,
    sla_hours   INTEGER      NOT NULL CHECK (sla_hours > 0),
    active      BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_complaint_category_name UNIQUE (society_id, name)
);

CREATE SEQUENCE complaint_id_seq;

CREATE TABLE complaint (
    id           BIGINT        PRIMARY KEY,
    society_id   BIGINT        NOT NULL,
    scope        VARCHAR(20)   NOT NULL CHECK (scope IN ('FLAT', 'COMMON_AREA')),
    tower_id     BIGINT,
    flat_id      BIGINT,
    category_id  BIGINT        NOT NULL REFERENCES complaint_category (id),
    title        VARCHAR(150)  NOT NULL,
    description  VARCHAR(2000),
    status       VARCHAR(20)   NOT NULL
        CHECK (status IN ('OPEN', 'ASSIGNED', 'IN_PROGRESS', 'RESOLVED', 'CLOSED', 'REJECTED')),
    raised_by    BIGINT        NOT NULL,
    assigned_to  BIGINT,
    raised_at    TIMESTAMPTZ   NOT NULL,
    due_at       TIMESTAMPTZ   NOT NULL,
    CONSTRAINT ck_complaint_location CHECK (
        (scope = 'FLAT' AND flat_id IS NOT NULL AND tower_id IS NOT NULL)
        OR (scope = 'COMMON_AREA' AND flat_id IS NULL))
);

CREATE INDEX ix_complaint_society_raised ON complaint (society_id, raised_at DESC);
CREATE INDEX ix_complaint_society_status ON complaint (society_id, status, raised_at DESC);
CREATE INDEX ix_complaint_society_tower ON complaint (society_id, tower_id, raised_at DESC);

CREATE TABLE complaint_status_history (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    complaint_id  BIGINT       NOT NULL REFERENCES complaint (id),
    sequence_no   INTEGER      NOT NULL,
    from_status   VARCHAR(20),
    to_status     VARCHAR(20)  NOT NULL,
    changed_by    BIGINT       NOT NULL,
    changed_at    TIMESTAMPTZ  NOT NULL,
    note          VARCHAR(500),
    CONSTRAINT uq_complaint_status_history_seq UNIQUE (complaint_id, sequence_no)
);
