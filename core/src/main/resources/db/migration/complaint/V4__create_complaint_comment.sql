-- The conversation on a complaint. Comments are never edited or deleted; author_id belongs to the Identity context.

CREATE TABLE complaint_comment (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    complaint_id  BIGINT         NOT NULL REFERENCES complaint (id),
    sequence_no   INTEGER        NOT NULL CHECK (sequence_no BETWEEN 1 AND 200),
    author_id     BIGINT         NOT NULL,
    text          VARCHAR(1000)  NOT NULL,
    posted_at     TIMESTAMPTZ    NOT NULL,
    CONSTRAINT uq_complaint_comment_seq UNIQUE (complaint_id, sequence_no)
);
