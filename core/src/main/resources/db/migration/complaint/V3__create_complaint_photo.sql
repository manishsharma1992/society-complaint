-- Photos attached to a complaint. The image lives in object storage (private bucket); only its key is stored here.

CREATE TABLE complaint_photo (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    complaint_id  BIGINT        NOT NULL REFERENCES complaint (id),
    position      INTEGER       NOT NULL CHECK (position BETWEEN 1 AND 5),
    storage_key   VARCHAR(300)  NOT NULL,
    content_type  VARCHAR(50)   NOT NULL CHECK (content_type IN ('image/jpeg', 'image/png', 'image/webp')),
    size_bytes    BIGINT        NOT NULL CHECK (size_bytes > 0),
    uploaded_by   BIGINT        NOT NULL,
    uploaded_at   TIMESTAMPTZ   NOT NULL,
    CONSTRAINT uq_complaint_photo_position UNIQUE (complaint_id, position),
    CONSTRAINT uq_complaint_photo_key UNIQUE (storage_key)
);
