-- Public Feed context. Lives in the "feed" schema (set by Flyway).
-- society_id, author_id, tower_id and moderator_id belong to other contexts: plain columns, no foreign keys.
-- author_id is the only link to who wrote a post. It must never leave this context (no API response, no log line).

CREATE SEQUENCE post_id_seq;

CREATE TABLE post (
    id            BIGINT        PRIMARY KEY,
    society_id    BIGINT        NOT NULL,
    slug          VARCHAR(12)   NOT NULL,
    author_id     BIGINT        NOT NULL,
    title         VARCHAR(150)  NOT NULL,
    body          VARCHAR(4000) NOT NULL,
    tower_id      BIGINT,
    tower_label   VARCHAR(120),
    status        VARCHAR(20)   NOT NULL,
    submitted_at  TIMESTAMPTZ   NOT NULL,
    published_at  TIMESTAMPTZ,
    CONSTRAINT uq_post_slug UNIQUE (slug),
    CONSTRAINT ck_post_tower CHECK ((tower_id IS NULL) = (tower_label IS NULL))
);

CREATE INDEX ix_post_society_status ON post (society_id, status, published_at DESC);
CREATE INDEX ix_post_author ON post (author_id, submitted_at DESC);

-- Append-only moderation log: who (moderator_id; NULL for the author's submission or a hide by reports),
-- what (from -> to), when, why. The application only ever inserts rows here.
CREATE TABLE post_moderation (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id       BIGINT       NOT NULL REFERENCES post (id),
    sequence_no   INTEGER      NOT NULL,
    from_status   VARCHAR(20),
    to_status     VARCHAR(20)  NOT NULL,
    moderator_id  BIGINT,
    moderated_at  TIMESTAMPTZ  NOT NULL,
    reason        VARCHAR(500),
    CONSTRAINT uq_post_moderation_seq UNIQUE (post_id, sequence_no)
);

-- Open reports (since the post was last published). reporter_key is a keyed hash, never an address.
CREATE TABLE post_report (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id       BIGINT        NOT NULL REFERENCES post (id),
    reporter_key  VARCHAR(100)  NOT NULL,
    reason        VARCHAR(500)  NOT NULL,
    reported_at   TIMESTAMPTZ   NOT NULL,
    CONSTRAINT uq_post_report_reporter UNIQUE (post_id, reporter_key)
);
