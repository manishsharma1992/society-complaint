-- Photos documenting a post. The images live in the private bucket; only their keys are stored here.
CREATE TABLE post_evidence (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id       BIGINT        NOT NULL REFERENCES post (id),
    position      INTEGER       NOT NULL,
    storage_key   VARCHAR(300)  NOT NULL,
    content_type  VARCHAR(20)   NOT NULL,
    size_bytes    BIGINT        NOT NULL,
    width_px      INTEGER       NOT NULL,
    height_px     INTEGER       NOT NULL,
    uploaded_at   TIMESTAMPTZ   NOT NULL,
    CONSTRAINT uq_post_evidence_key UNIQUE (storage_key),
    CONSTRAINT uq_post_evidence_position UNIQUE (post_id, position)
);
