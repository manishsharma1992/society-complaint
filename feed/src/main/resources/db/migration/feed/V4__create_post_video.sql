-- Videos documenting a post. The original upload, its re-encoded copy (<key>-play.mp4) and its poster frame
-- (<key>-poster.jpg) live in the private bucket; only the original's key is stored here. Only the re-encoded copy
-- of a READY video is ever shown: the original may carry the phone's location.
CREATE TABLE post_video (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id         BIGINT        NOT NULL REFERENCES post (id),
    position        INTEGER       NOT NULL,
    storage_key     VARCHAR(300)  NOT NULL,
    content_type    VARCHAR(20)   NOT NULL,
    size_bytes      BIGINT        NOT NULL,
    uploaded_at     TIMESTAMPTZ   NOT NULL,
    status          VARCHAR(20)   NOT NULL,
    width_px        INTEGER,
    height_px       INTEGER,
    duration_ms     BIGINT,
    failure_reason  VARCHAR(300),
    CONSTRAINT uq_post_video_key UNIQUE (storage_key),
    CONSTRAINT uq_post_video_position UNIQUE (post_id, position),
    CONSTRAINT ck_post_video_status CHECK (status IN ('PROCESSING', 'READY', 'FAILED')),
    CONSTRAINT ck_post_video_ready CHECK ((status = 'READY') = (duration_ms IS NOT NULL)),
    CONSTRAINT ck_post_video_failed CHECK ((status = 'FAILED') = (failure_reason IS NOT NULL))
);

-- Finds videos left PROCESSING (e.g. by a restart) without scanning every video.
CREATE INDEX ix_post_video_processing ON post_video (status) WHERE status = 'PROCESSING';
