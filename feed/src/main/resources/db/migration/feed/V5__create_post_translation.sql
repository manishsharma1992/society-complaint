-- Machine translations of published posts, made when a reader first asks for one and kept, so each post is sent
-- to the translation service at most once per language. TEXT: a translation can be longer than the original.
CREATE TABLE post_translation (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id        BIGINT       NOT NULL REFERENCES post (id),
    language       VARCHAR(2)   NOT NULL,
    title          TEXT         NOT NULL,
    body           TEXT         NOT NULL,
    translated_at  TIMESTAMPTZ  NOT NULL,
    CONSTRAINT uq_post_translation_language UNIQUE (post_id, language)
);
