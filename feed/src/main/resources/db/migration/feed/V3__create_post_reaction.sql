-- Emoji reactions to published posts. Anyone can react, even without logging in: reactor_key is a keyed hash of
-- the visitor's address and the post, never an address or a user. One reaction per reactor and post.
CREATE TABLE post_reaction (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id       BIGINT        NOT NULL REFERENCES post (id),
    reactor_key   VARCHAR(100)  NOT NULL,
    emoji         VARCHAR(20)   NOT NULL,
    reacted_at    TIMESTAMPTZ   NOT NULL,
    CONSTRAINT uq_post_reaction_reactor UNIQUE (post_id, reactor_key)
);
