-- Identity & Access context. Lives in the "identity" schema (set by Flyway).
-- Personal data is limited to what the society needs (India DPDP Act): phone number and name.
-- society_id, tower_id and flat_id belong to the Residency context: plain columns, no foreign keys.

CREATE SEQUENCE app_user_id_seq START WITH 100;

CREATE TABLE app_user (
    id                BIGINT        PRIMARY KEY,
    phone             VARCHAR(13)   NOT NULL,
    name              VARCHAR(100),
    status            VARCHAR(10)   NOT NULL CHECK (status IN ('VERIFIED', 'PENDING', 'ACTIVE', 'REJECTED')),
    claim_society_id  BIGINT,
    claim_flat_id     BIGINT,
    claim_occupancy   VARCHAR(10)   CHECK (claim_occupancy IN ('OWNER', 'TENANT')),
    rejection_reason  VARCHAR(500),
    created_at        TIMESTAMPTZ   NOT NULL,
    CONSTRAINT uq_app_user_phone UNIQUE (phone),
    CONSTRAINT ck_app_user_claim CHECK (
        (claim_society_id IS NULL AND claim_flat_id IS NULL AND claim_occupancy IS NULL)
        OR (claim_society_id IS NOT NULL AND claim_flat_id IS NOT NULL AND claim_occupancy IS NOT NULL))
);

CREATE INDEX ix_app_user_pending ON app_user (claim_society_id, created_at) WHERE status = 'PENDING';

CREATE TABLE user_role (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT       NOT NULL REFERENCES app_user (id),
    role        VARCHAR(20)  NOT NULL CHECK (role IN ('RESIDENT', 'STAFF', 'TOWER_ADMIN', 'SOCIETY_ADMIN')),
    society_id  BIGINT       NOT NULL,
    tower_id    BIGINT,
    CONSTRAINT uq_user_role UNIQUE NULLS NOT DISTINCT (user_id, role, society_id, tower_id)
);

-- The latest code per phone number; only a keyed hash of the code is stored.
CREATE TABLE otp_challenge (
    phone            VARCHAR(13)   PRIMARY KEY,
    code_hash        VARCHAR(100)  NOT NULL,
    expires_at       TIMESTAMPTZ   NOT NULL,
    failed_attempts  INTEGER       NOT NULL,
    used             BOOLEAN       NOT NULL,
    last_sent_at     TIMESTAMPTZ   NOT NULL,
    window_start     TIMESTAMPTZ   NOT NULL,
    sends_in_window  INTEGER       NOT NULL
);
